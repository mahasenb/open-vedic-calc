#!/usr/bin/env python3
"""Record an INDEPENDENTLY-SOURCED reference corpus from NASA/JPL Horizons.

Why this exists
---------------
``tests/goldens/swiss_ephemeris_goldens.json`` is recorded by running this engine
and writing down what it said (``UPDATE_SWISS_GOLDENS=1``). That is a perfectly
good *regression* detector — it catches the engine's numbers moving — but it
cannot detect that the numbers were wrong on the day they were recorded, because
the expected value and the observed value come from the same code. A golden
generated by the code under test proves only self-consistency.

This corpus is different: every expected value is fetched from **NASA/JPL
Horizons**, an authority entirely outside this repository's dependency set. It is
the reference implementation of the solar-system ephemeris (DE441) that the Swiss
Ephemeris data files are themselves a compression of, evaluated on JPL's own
servers by JPL's own code. Agreement between the two is therefore evidence about
*this engine's pipeline* — body identity, the sidereal conversion, the ayanamsa,
the lunar-node model, the Julian-Day transport — and not merely evidence that the
engine is reproducible.

WHAT IS FETCHED, AND IN WHICH FRAME
-----------------------------------
1. ``tropical_apparent_longitude_deg`` — for the seven visible grahas, Horizons'
   ``QUANTITIES='31'`` (``ObsEcLon``) observer quantity: apparent geocentric
   ecliptic longitude referred to the ecliptic and equinox **of date**, centred on
   ``500@399`` (the geocentre). That is precisely the frame and the corrections
   (light-time, aberration, relativistic deflection, nutation) that
   ``swe.calc_ut(..., FLG_SWIEPH | FLG_SIDEREAL)`` produces before the ayanamsa is
   subtracted, so the comparison is like-for-like.

2. ``moon_osculating_node_j2000_deg`` — Horizons' ``EPHEM_TYPE='ELEMENTS'``
   ``OM`` (longitude of the ascending node) for the Moon (301) about the Earth
   (500@399), ``REF_PLANE='ECLIPTIC'``. Horizons reports osculating elements in the
   **ecliptic of J2000.0** and accepts only TDB for them, which is why each epoch
   carries a ``jd_tdb`` alongside its ``jd_ut``.

   This is the external pin on the **lunar node**, the graha with by far the worst
   model and ephemeris-source exposure (``CLAUDE.md``: up to 1.981465100 deg between
   the true and mean models). The engine's declared node
   (``bphs_core.utils.LUNAR_NODE_BODY``) is compared against it in the J2000 frame,
   where JPL publishes it, so no frame rotation of ours sits between the two values.
   ``tests/test_lunar_node_model.py`` separately proves the served chart uses that
   same declared body, so the two contracts together carry JPL's number all the way
   to what a caller receives.

WHAT IS NOT FETCHED
-------------------
The **ayanamsa** has no counterpart in Horizons: it is an astrological convention
(the Lahiri/Chitrapaksha sidereal zero point fixed by the Indian Calendar Reform
Committee), not an astronomical observable, and no solar-system ephemeris publishes
it. It is therefore recorded here as ``ayanamsa_deg`` with
``"source": "engine"`` and is explicitly NOT an independent expected value — see the
provenance block written into the corpus, and the test module's docstring for what
the corpus does and does not establish about it.

USAGE
-----
    python ci/fetch_reference_corpus.py            # re-record from Horizons
    python ci/fetch_reference_corpus.py --check    # fetch and diff, write nothing

Network access is required to RE-RECORD. The committed corpus is read offline by
``tests/test_independent_reference_corpus.py``; the test never calls the network.
"""
from __future__ import annotations

import argparse
import datetime
import json
import pathlib
import re
import sys
import urllib.parse
import urllib.request

HORIZONS_API = "https://ssd.jpl.nasa.gov/api/horizons.api"
GEOCENTRE = "500@399"

CORPUS_PATH = pathlib.Path(__file__).resolve().parent.parent / "tests" / "goldens" / "independent_reference_corpus.json"

# Horizons target ids. These are BODY CENTRES (199/299/499/599/699), never the
# system barycentres (1/2/4/5/6) — swisseph returns body centres, and mixing the
# two would inject a real, if small, offset for the outer planets.
HORIZONS_TARGET = {
    "Sun": "10",
    "Moon": "301",
    "Mercury": "199",
    "Venus": "299",
    "Mars": "499",
    "Jupiter": "599",
    "Saturn": "699",
}
MOON_TARGET = "301"

# The seven visible grahas. Rahu and Ketu are pinned by the node query instead:
# neither is a body Horizons knows, because neither is a body.
VISIBLE_GRAHAS = ("Sun", "Moon", "Mars", "Mercury", "Jupiter", "Venus", "Saturn")

# ---------------------------------------------------------------------------
# Epochs — synthetic and non-personal, every one chosen for a stated astronomical
# reason. No real birth data of any person appears here or may ever be added:
# the workspace rule is absolute (CLAUDE.md, "Determinism").
# ---------------------------------------------------------------------------
